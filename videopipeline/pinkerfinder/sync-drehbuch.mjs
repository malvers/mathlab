// Copies Solita's lines from narration.mjs into the drehbuch page, so the
// spoken text has exactly one source. Run after every change to narration.mjs:
//
//     node videopipeline/pinkerfinder/sync-drehbuch.mjs
//
// It rewrites only what sits between the SAY:START / SAY:END markers in
// HTML/drehbuch/pinkerfinder.html - everything else in that file is hand-written.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { NARRATION } from './narration.mjs';
import { workDir } from '../lib/paths.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PAGE = path.resolve(HERE, '../../HTML/drehbuch/pinkerfinder.html');

// Once run1 has spoken the script, the plot's estimated seconds are superseded by
// what Solita actually took. Feeding those back keeps the timeline honest.
let durs = {};
try { durs = JSON.parse(fs.readFileSync(`${workDir('pinkerfinder')}/durs.json`, 'utf8')); }
catch (e) { /* not spoken yet - the page keeps the planned seconds */ }

/** SSML -> readable HTML. The pauses stay visible: they are stage directions,
 *  not padding - run2 performs the action inside them. */
function toHtml(ssml) {
    return ssml
        .replace(/^<speak>|<\/speak>$/g, '')
        // long gaps are stage directions and get a mark; the short ones are stress
        // (Studio voices reject <emphasis>, so a break in front of the word does it)
        .replace(/<break\s+time="(\d+)ms"\s*\/>/g, (_, ms) => +ms >= 700
            ? ` <span class="pause">${(+ms / 1000).toFixed(1).replace('.', ',')} s</span> `
            : '<span class="beat"></span>')
        .replace(/<say-as[^>]*>(.*?)<\/say-as>/g, '<span class="spell">$1</span>')
        .replace(/\s{2,}/g, ' ')
        .trim();
}

const entries = Object.entries(NARRATION)
    .map(([k, v]) => `    ${k}: '${toHtml(v).replace(/'/g, "\\'")}'`)
    .join(',\n');

const spoken = Object.keys(durs).length
    ? `const SPOKEN = ${JSON.stringify(durs)};\n`
    : `const SPOKEN = {};\n`;

const block =
    `/* SAY:START - generated by videopipeline/pinkerfinder/sync-drehbuch.mjs, do not edit */\n` +
    `const SAY = {\n${entries}\n};\n` + spoken +
    `/* SAY:END */`;

const page = fs.readFileSync(PAGE, 'utf8');
const re = /\/\* SAY:START[\s\S]*?\/\* SAY:END \*\//;
if (!re.test(page)) {
    console.error('markers SAY:START / SAY:END not found in ' + PAGE);
    process.exit(1);
}
fs.writeFileSync(PAGE, page.replace(re, block));
const total = Object.values(durs).reduce((a, b) => a + b, 0);
console.log(`synced ${Object.keys(NARRATION).length} scenes into ${path.relative(process.cwd(), PAGE)}` +
    (total ? ` — gesprochen ${Math.floor(total / 60)}:${String(Math.round(total % 60)).padStart(2, '0')}` : ''));
